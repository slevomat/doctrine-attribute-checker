<?php declare(strict_types = 1);

namespace Slevomat\DoctrineAttributeChecker\Checker;

use Slevomat\DoctrineAttributeChecker\Checker\Data\Insert\InsertArticleEntity;
use Slevomat\DoctrineAttributeChecker\Checker\Data\Insert\InsertTagEntity;
use Slevomat\DoctrineAttributeChecker\Database\DatabaseColumn;
use Slevomat\DoctrineAttributeChecker\Database\DatabaseSchemaSnapshot;

final class DatabaseIdentityColumnTest extends FactoryMetadataTestCase
{

	private const string FILE = __DIR__ . '/data/Insert/InsertEntities.php';

	public function testAutoIncrementIdentityColumnIsAccepted(): void
	{
		self::assertSame([], $this->inspectRule(InsertArticleEntity::class, true));
	}

	public function testIdentityColumnWithoutAutoIncrementIsReported(): void
	{
		self::assertSame(
			['Identifier column insert_article.id is generated by the database, but it is not AUTO_INCREMENT.'],
			$this->inspectRule(InsertArticleEntity::class, false),
		);
	}

	public function testIdentifierWithoutGeneratedValueIsNotChecked(): void
	{
		self::assertSame([], $this->inspectRule(InsertTagEntity::class, false));
	}

	/**
	 * @param class-string $className
	 * @return list<string>
	 */
	private function inspectRule(string $className, bool $autoIncrement): array
	{
		$result = $this->inspectFixture(
			__DIR__ . '/data/Insert',
			self::FILE,
			$className,
			$this->createIdentitySchema($autoIncrement),
			false,
		);

		$messages = [];
		foreach ($result['violations'] as $violation) {
			if ($violation->rule !== 'database.identity-auto-increment') {
				continue;
			}

			$messages[] = $violation->message;
		}

		return $messages;
	}

	private function createIdentitySchema(bool $autoIncrement): DatabaseSchemaSnapshot
	{
		return $this->createSchema([
			'insert_article.id' => new DatabaseColumn('int', 'int', null, 10, 0, false, null, autoIncrement: $autoIncrement),
			'insert_article.title' => self::varcharColumn(20, false),
			'insert_article.main_tag_id' => self::charColumn(36, true),
			'insert_tag.id' => self::charColumn(36, false),
		]);
	}

}
