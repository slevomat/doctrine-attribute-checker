<?php declare(strict_types = 1);

namespace Slevomat\DoctrineAttributeChecker\Rule\Database;

use Doctrine\ORM\Mapping\ClassMetadata;
use Doctrine\ORM\Mapping\ManyToManyOwningSideMapping;
use Doctrine\ORM\Mapping\ToOneOwningSideMapping;
use Override;
use Slevomat\DoctrineAttributeChecker\Checker\ClassContext;
use Slevomat\DoctrineAttributeChecker\Checker\Identifiers;
use Slevomat\DoctrineAttributeChecker\Checker\ViolationReporter;
use Slevomat\DoctrineAttributeChecker\Configuration\Configuration;
use Slevomat\DoctrineAttributeChecker\Database\DatabaseSchemaSnapshot;
use Slevomat\DoctrineAttributeChecker\Rule\ClassRule;
use function is_string;
use function sprintf;
use function strtolower;

/**
 * @phpstan-type EntityClassMetadata ClassMetadata<object>
 */
final class DatabaseColumnNotInsertedRule implements ClassRule
{

	public function __construct(
		private DatabaseSchemaSnapshot $databaseSchema,
	)
	{
	}

	#[Override]
	public static function getIdentifiers(Configuration $configuration): array
	{
		return ['database.column-not-inserted'];
	}

	#[Override]
	public function process(ClassContext $context, ViolationReporter $reporter): void
	{
		$classMetadata = $context->classMetadata;
		if (
			$classMetadata->isMappedSuperclass
			|| $classMetadata->isEmbeddedClass
			|| $classMetadata->isInheritanceTypeJoined()
			|| $context->reflectionClass->isAbstract()
		) {
			return;
		}

		$tableSchema = $classMetadata->table['schema'] ?? null;
		if (is_string($tableSchema) && $tableSchema !== $this->databaseSchema->getSchema()) {
			return;
		}

		$this->checkTable(
			$context,
			$reporter,
			$classMetadata->getTableName(),
			$this->getInsertedColumns($classMetadata),
			$context->className,
		);

		foreach ($classMetadata->associationMappings as $associationMapping) {
			if (!$associationMapping instanceof ManyToManyOwningSideMapping) {
				continue;
			}

			$insertedColumns = [];
			foreach ($associationMapping->joinTable->joinColumns as $joinColumn) {
				$insertedColumns[self::normalize($joinColumn->name)] = true;
			}

			foreach ($associationMapping->joinTable->inverseJoinColumns as $joinColumn) {
				$insertedColumns[self::normalize($joinColumn->name)] = true;
			}

			$this->checkTable(
				$context,
				$reporter,
				$associationMapping->joinTable->name,
				$insertedColumns,
				sprintf('%s::$%s', $context->className, $associationMapping->fieldName),
			);
		}
	}

	/**
	 * @param array<string, true> $insertedColumns
	 */
	private function checkTable(
		ClassContext $context,
		ViolationReporter $reporter,
		string $tableName,
		array $insertedColumns,
		string $target,
	): void
	{
		foreach ($this->databaseSchema->getColumns($tableName) as $columnName => $column) {
			if (
				$column->nullable
				|| $column->hasDefault
				|| $column->autoIncrement
				|| $column->generated
				|| isset($insertedColumns[self::normalize($columnName)])
			) {
				continue;
			}

			$reporter->addViolationAt(
				$context->file,
				$context->classNode->getStartLine(),
				$target,
				'database.column-not-inserted',
				sprintf(
					'Column %s.%s is NOT NULL without a default value, but %s does not insert it.',
					Identifiers::unquote($tableName),
					$columnName,
					$target,
				),
				false,
			);
		}
	}

	/**
	 * An identifier generated by the database counts as inserted, because its missing auto-increment is reported
	 * by another rule.
	 *
	 * @param EntityClassMetadata $classMetadata
	 * @return array<string, true>
	 */
	private function getInsertedColumns(ClassMetadata $classMetadata): array
	{
		$columns = [];
		foreach ($classMetadata->fieldMappings as $fieldMapping) {
			if ($fieldMapping->notInsertable === true) {
				continue;
			}

			$columns[self::normalize($fieldMapping->columnName)] = true;
		}

		foreach ($classMetadata->associationMappings as $associationMapping) {
			if (!$associationMapping instanceof ToOneOwningSideMapping) {
				continue;
			}

			foreach ($associationMapping->joinColumns as $joinColumn) {
				$columns[self::normalize($joinColumn->name)] = true;
			}
		}

		if ($classMetadata->discriminatorColumn !== null) {
			$columns[self::normalize($classMetadata->discriminatorColumn->name)] = true;
		}

		return $columns;
	}

	private static function normalize(string $columnName): string
	{
		return strtolower(Identifiers::unquote($columnName));
	}

}
